#!/usr/bin/env bash
# ReKernel-X 集成：把上游 LKM-Source 落进 drivers/rekernel_x，生成 in-tree Kconfig/Makefile，
# 摘掉厂商树里预置的 Re-Kernel，写 CONFIG_REKERNEL_X=y。
#
# 用法: apply_rekernel_x.sh <kernel_workspace> [repo] [ref]
#   <kernel_workspace>  含 common/ 的那一层（CI 是 $GITHUB_WORKSPACE/kernel_workspace）
#   repo                默认 myflavor/ReKernel-X
#   ref                 默认 main
#
# 上游是外置 LKM 包（obj-m 形态、没有 Kconfig），落到内核树后必须改成 in-tree 规则，
# 否则 make 只看到一个孤立的 .ko 规则，Image 里什么都没有。
set -euo pipefail

KW="${1:?用法: apply_rekernel_x.sh <kernel_workspace> [repo] [ref]}"
REPO="${2:-myflavor/ReKernel-X}"
REF="${3:-main}"

cd "$KW"

# ReKernel-X 依赖 android_vh_binder_* / android_vh_do_send_sig_info，5.10 以下不存在
KVER_MAJOR=$(awk '/^VERSION =/{print $3; exit}' common/Makefile)
KVER_PATCH=$(awk '/^PATCHLEVEL =/{print $3; exit}' common/Makefile)
if [ -z "$KVER_MAJOR" ] || [ -z "$KVER_PATCH" ]; then
  echo "ERROR: 无法从 common/Makefile 解析内核版本" >&2
  exit 1
fi
if [ "$KVER_MAJOR" -lt 5 ] || { [ "$KVER_MAJOR" -eq 5 ] && [ "$KVER_PATCH" -lt 10 ]; }; then
  echo "内核 $KVER_MAJOR.$KVER_PATCH < 5.10，ReKernel-X 不适用，跳过"
  if [ -n "${GITHUB_ENV:-}" ]; then echo "RKX_SKIPPED_VERSION=true" >> "$GITHUB_ENV"; fi
  exit 0
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP" 2>/dev/null || true' EXIT
git clone --depth 1 --branch "$REF" "https://github.com/$REPO.git" "$TMP/rkx"
RKX_COMMIT=$(git -C "$TMP/rkx" rev-parse --short HEAD)
echo "ReKernel-X upstream: $REPO@$RKX_COMMIT"

RKX_DIR=common/drivers/rekernel_x
rm -rf "$RKX_DIR"
mkdir -p "$RKX_DIR"
cp -a "$TMP/rkx/LKM-Source/." "$RKX_DIR/"

# 上游没有 Kconfig（外置模块靠 arch 的 obj-m 编译），in-tree 必须自建
{
  echo 'config REKERNEL_X'
  echo '	bool "ReKernel-X: binder / signal / network runtime hooks"'
  echo '	default n'
  echo '	help'
  echo '	  ReKernel-X 内核侧运行时钩子：Binder 事务与异步缓存清理、信号投递、'
  echo '	  网络回流事件，经 Generic Netlink 上报用户态模块。'
  echo ''
  echo 'config REKERNEL_X_DEBUG'
  echo '	bool "ReKernel-X debug logging"'
  echo '	depends on REKERNEL_X'
  echo '	default n'
  echo '	help'
  echo '	  打开 rkx_log_debug（正式包不要开，会持续打印）。'
} > "$RKX_DIR/Kconfig"

# 外置模块 Makefile -> in-tree 规则；上游版本号写进 ccflags
{
  echo '# ReKernel-X in-tree build rules (generated by apply_rekernel_x.sh)'
  echo 'obj-$(CONFIG_REKERNEL_X) += rekernel_x.o'
  echo ''
  echo 'rekernel_x-y := rkx.o rkx_genl.o rkx_netuid.o rkx_free_async.o rkx_frozen.o \'
  echo '                rkx_binder.o rkx_signal.o rkx_netfilter.o rkx_binder_kp.o rkx_binder_alloc.o'
  echo ''
  printf 'ccflags-y += -DRKX_VERSION=\\"%s\\"\n' "$RKX_COMMIT"
  echo 'ccflags-$(CONFIG_REKERNEL_X_DEBUG) += -DRKX_DEBUG'
} > "$RKX_DIR/Makefile"

# 摘掉厂商树预置的 Re-Kernel：CONFIG_REKERNEL 不再启用，留着是死代码，
# 两套 binder 钩子并存时一旦被 defconfig 重新打开会互相干扰
rm -rf common/drivers/rekernel
sed -i '/^#Re-Kernel Support$/d' common/drivers/Makefile
sed -i 's|^obj-$(CONFIG_REKERNEL)[[:space:]]*+= rekernel/|obj-$(CONFIG_REKERNEL_X) += rekernel_x/|' common/drivers/Makefile
sed -i 's|^source "drivers/rekernel/Kconfig"$|source "drivers/rekernel_x/Kconfig"|' common/drivers/Kconfig
sed -i '/^CONFIG_REKERNEL=y$/d' common/arch/arm64/configs/gki_defconfig

# 结构不符预期时补挂一次（幂等）
grep -qF 'source "drivers/rekernel_x/Kconfig"' common/drivers/Kconfig || \
  sed -i '/^endmenu$/i source "drivers/rekernel_x/Kconfig"' common/drivers/Kconfig
grep -qF 'obj-$(CONFIG_REKERNEL_X) += rekernel_x/' common/drivers/Makefile || \
  echo 'obj-$(CONFIG_REKERNEL_X) += rekernel_x/' >> common/drivers/Makefile

# 6.1 的 binder_internal.h 用到 DEFINE_SHOW_ATTRIBUTE，需要先引入 seq_file.h（幂等）
for f in rkx_binder.c rkx_binder_kp.c rkx_binder_alloc.h; do
  grep -qF '#include <linux/seq_file.h>' "$RKX_DIR/$f" && continue
  sed -i '/#include "\.\.\/android\/binder_internal\.h"/i #include <linux/seq_file.h>' "$RKX_DIR/$f"
done

grep -q '^CONFIG_REKERNEL_X=y$' common/arch/arm64/configs/gki_defconfig || \
  echo "CONFIG_REKERNEL_X=y" >> common/arch/arm64/configs/gki_defconfig

# 落盘自检：缺一处说明补丁没打全，直接失败
for f in "$RKX_DIR/Kconfig" "$RKX_DIR/Makefile" "$RKX_DIR/rkx.c"; do
  [ -f "$f" ] || { echo "ERROR: ReKernel-X 未落盘: $f" >&2; exit 1; }
done
grep -q '^obj-$(CONFIG_REKERNEL_X) += rekernel_x.o$' "$RKX_DIR/Makefile" || {
  echo "ERROR: 生成的 Makefile 规则不对" >&2; exit 1; }

# 注意：这里不能写 `[ -n "$X" ] && echo`，set -e 下条件为假会让整个脚本退出
if [ -n "${GITHUB_ENV:-}" ]; then
  echo "RKX_VERSION_SHORT=$RKX_COMMIT" >> "$GITHUB_ENV"
fi
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  echo "" >> "$GITHUB_STEP_SUMMARY"
  echo "> ✅ **ReKernel-X** 已集成：upstream \`$RKX_COMMIT\`（Linux $KVER_MAJOR.$KVER_PATCH）" >> "$GITHUB_STEP_SUMMARY"
fi
echo "ReKernel-X 集成完成（$RKX_COMMIT）"
